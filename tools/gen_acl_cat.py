#!/usr/bin/env python3
"""Generate src/acl_cat_data.h, the built-in table behind ACL CAT [category].

Asks a real Valkey node (load the same modules the cluster runs, e.g.
bloom/json/search, so their categories show up) for ACL CAT and ACL CAT <cat>
for every category, then keeps only the commands docs/COMMANDS.md lists as
supported (every table before "## Unsupported commands", minus rows whose
notes start with "Planned"). Container subcommands are matched in Valkey's
"cmd|sub" form ("ACL WHOAMI" -> "acl|whoami"). Category order and each
category's command order and spelling are kept as the server returns them.

Re-run after adding a command to COMMANDS.md, pointing it at a node that
loads the bloom/json/search modules:
    tools/gen_acl_cat.py --host <valkey-host> --port <port>
"""
import argparse
import os
import re
import socket
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


class Resp:
    def __init__(self, host, port):
        self.sock = socket.create_connection((host, port), timeout=10)
        self.f = self.sock.makefile("rb")

    def cmd(self, *args):
        out = b"*%d\r\n" % len(args)
        for a in args:
            a = a.encode()
            out += b"$%d\r\n%s\r\n" % (len(a), a)
        self.sock.sendall(out)
        return self._read()

    def _read(self):
        line = self.f.readline().rstrip(b"\r\n")
        t, rest = line[:1], line[1:]
        if t in (b"+", b":"):
            return rest.decode()
        if t == b"-":
            raise RuntimeError(rest.decode())
        if t == b"$":
            n = int(rest)
            if n < 0:
                return None
            data = self.f.read(n + 2)[:-2]
            return data.decode()
        if t == b"*":
            return [self._read() for _ in range(int(rest))]
        raise RuntimeError("unexpected reply %r" % line)


def supported_names(path):
    names = set()
    with open(path) as f:
        for line in f:
            if line.startswith("## Unsupported"):
                break
            m = re.match(r"^\| `([^`]+)` \|(.*)\|\s*$", line)
            if not m:
                continue
            if m.group(2).strip().startswith("Planned"):
                continue
            words = m.group(1).split()
            names.add("|".join(words).lower())
    return names


def c_ident(cat):
    return "ACL_CAT_" + re.sub(r"[^A-Za-z0-9]", "_", cat).upper()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=6379)
    ap.add_argument("--commands-md", default=os.path.join(ROOT, "docs", "COMMANDS.md"))
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "acl_cat_data.h"))
    args = ap.parse_args()

    supported = supported_names(args.commands_md)
    r = Resp(args.host, args.port)
    version = next((l.split(":", 1)[1] for l in r.cmd("INFO", "server").splitlines()
                    if l.startswith("valkey_version:")), "unknown")
    cats = r.cmd("ACL", "CAT")

    seen = set()
    out = []
    out.append("/* Generated by tools/gen_acl_cat.py from Valkey %s -- DO NOT EDIT. */" % version)
    out.append("/* Built-in table behind ACL CAT [category] (see src/acl_cat.c): each")
    out.append(" * category's commands, limited to what docs/COMMANDS.md lists as supported. */")
    out.append("")
    for cat in cats:
        cmds = [c for c in r.cmd("ACL", "CAT", cat) if c.lower() in supported]
        seen.update(c.lower() for c in cmds)
        out.append("static const char *%s[] = {" % c_ident(cat))
        for c in cmds:
            out.append('    "%s",' % c)
        out.append("    NULL};")
        out.append("")
    out.append("static const AclCategory ACL_CATEGORIES[] = {")
    for cat in cats:
        out.append('    {"%s", %s},' % (cat, c_ident(cat)))
    out.append("    {NULL, NULL}};")

    with open(args.out, "w") as f:
        f.write("\n".join(out) + "\n")

    # Supported names no category mentions: typos in COMMANDS.md, or
    # container commands only listed as a bare name (Valkey categorises
    # their subcommands instead).
    missing = sorted(supported - seen)
    if missing:
        print("note: not in any category: " + " ".join(missing), file=sys.stderr)
    print("wrote %s (%d categories)" % (args.out, len(cats)))


if __name__ == "__main__":
    main()
